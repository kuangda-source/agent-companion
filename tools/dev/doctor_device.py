#!/usr/bin/env python3
"""Read-only board preparation and asset budget; does not open serial ports."""
import argparse
from datetime import datetime, timezone
import glob
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument("--output",type=Path,default=ROOT/"reports/BOARD_READINESS.json")
args=parser.parse_args()
spec=json.loads((ROOT/"device-toolchain.lock.json").read_text())
sdk=ROOT/".deps"/("esp-idf-v"+spec["esp_idf"]["version"])
def run(command):
    try:
        result=subprocess.run(command,capture_output=True,text=True,timeout=15)
        return result.stdout.strip() if result.returncode==0 else None
    except (OSError,subprocess.TimeoutExpired):
        return None
fonts=[]
for path in sorted((ROOT/"generated/fonts").glob("*.c")):
    source=path.read_text()
    match=re.search(r"const uint8_t glyph_bitmap\[\].*?=\s*\{(.*?)\};",source,re.S)
    if not match: raise RuntimeError("Missing font bitmap: "+str(path))
    fonts.append({"file":path.name,"bitmap_bytes":len(re.findall(r"0x[0-9a-fA-F]+",match[1])),"source_sha256":hashlib.sha256(path.read_bytes()).hexdigest()})
pet_report=json.loads((ROOT/"reports/pet-build.json").read_text())
# The report shape is generated by the existing asset compiler.
pets=pet_report["packs"]
sprite_bytes=sum(p["pixel_payload_bytes"] for p in pets)
font_bytes=sum(f["bitmap_bytes"] for f in fonts)
revision=run(["git","-C",str(sdk),"rev-parse","HEAD"])
submodules=run(["git","-C",str(sdk),"submodule","status","--recursive"])
compiler_paths=list((ROOT/".tools/esp-idf/tools/riscv32-esp-elf").glob("*/riscv32-esp-elf/bin/riscv32-esp-elf-gcc"))
compiler=run([str(compiler_paths[-1]),"--version"]) if compiler_paths else None
ports=sorted(glob.glob("/dev/cu.*"))
builds={}
for profile in ["rev1_3","rev3_x"]:
    build=ROOT/f".build/device-{profile}"
    # Retain historical probe builds; never mistake one for the full viewer.
    viewer=build/"agent_companion_device.bin"
    binary=viewer if viewer.is_file() else build/"agent_companion_board_probe.bin"
    config=(build/"sdkconfig").read_text() if (build/"sdkconfig").exists() else ""
    expected="CONFIG_ESP32P4_REV_MIN_100=y" if profile=="rev1_3" else "CONFIG_ESP32P4_REV_MIN_300=y"
    builds[profile]={"program":"v1_device_viewer" if binary==viewer else "historical_board_probe",
      "binary_file":str(binary.relative_to(ROOT)),"binary_present":binary.is_file(),"binary_bytes":binary.stat().st_size if binary.is_file() else None,
      "binary_sha256":hashlib.sha256(binary.read_bytes()).hexdigest() if binary.is_file() else None,
      "profile_resolved":expected in config and ("CONFIG_ESP32P4_SELECTS_REV_LESS_V3=y" in config)==(profile=="rev1_3"),
      "hardware":"See BOARD_V1_LIVE_ACCEPTANCE_20261102 and REMOTE_CONNECTION_ACCEPTANCE_20261102; inventory is not hardware verification"}
packed={}
for kind in ["fonts","pets"]:
    path=ROOT/f".build/device-{kind}/report.json"
    if path.is_file():
        rows=json.loads(path.read_text())
        packed[kind]={"count":len(rows),"payload_bytes":sum(r["bitmap_bytes" if kind=="fonts" else "packed_bytes"] for r in rows),
          "lossless_or_coverage_preserved":all(r.get("lossless",r.get("glyph_coverage_preserved",False)) for r in rows)}
report={
    "generated_at":datetime.now(timezone.utc).isoformat(),"board":spec["board"],
    "hardware_status":"NOT_VERIFIED; preparation inventory only, see separate connected-board acceptance", "serial_ports":ports,
    "serial_port_note":"Inventory only. Bluetooth/debug ports are not evidence of an attached board.",
    "toolchain":{"idf_expected_commit":spec["esp_idf"]["commit"],"idf_actual_commit":revision,
      "idf_source_pinned":revision==spec["esp_idf"]["commit"],"submodules_complete":submodules is not None and not any(s.startswith(("-","+","U")) for s in submodules.splitlines()),
      "compiler":compiler.splitlines()[0] if compiler else None,
      "python_environments":[str(p.relative_to(ROOT)) for p in (ROOT/".tools/esp-idf/python_env").glob("*/bin/python")],
      "free_disk_bytes":shutil.disk_usage(ROOT).free},
    "versions":{"idf":spec["esp_idf"]["version"],"bsp":spec["bsp"]["version"],"lvgl":spec["lvgl"]},
    "assets":{"pets":pets,"sprite_bytes":sprite_bytes,"font_bitmaps":fonts,"font_bitmap_bytes":font_bytes,
      "pixel_payload_lower_bound_bytes":sprite_bytes+font_bytes,
      "device_compressed":packed,
      "note":"Raw and compressed payload lower bounds exclude descriptors/code/alignment. Use builds.binary_bytes for the linked image; neither measures RAM use."},
    "ram_plan":{"psram_bytes":spec["psram_bytes"],"rgb565_framebuffer_bytes":1024*600*2,
      "triple_framebuffer_bytes":3*1024*600*2,"two_60_line_draw_buffers_bytes":2*1024*60*2,
      "policy":"Flash-mapped read-only assets; do not copy the complete assets/code into PSRAM by default. Reserve >=8 MiB free PSRAM and >=128 KiB internal heap as bring-up targets, subject to measurement."},
    "flash_plan":{"bringup_app_partition_bytes":24*1024**2,"production_ota_slot_candidate_bytes":13*1024**2,
      "raw_assets_fit_ota_candidate":sprite_bytes+font_bytes<=13*1024**2,
      "ota_status":"NOT_IMPLEMENTED; lossless device compression enabled, but the full V1 image still exceeds a 13 MiB OTA slot"},
    "builds":builds,
}
args.output.parent.mkdir(parents=True,exist_ok=True)
args.output.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n")
print(json.dumps({"report":str(args.output),"toolchain":report["toolchain"],"sprite_mib":round(sprite_bytes/1024**2,2),"font_bitmap_mib":round(font_bytes/1024**2,2),"ota_raw_assets_fit":report["flash_plan"]["raw_assets_fit_ota_candidate"],"hardware":report["hardware_status"]},ensure_ascii=False,indent=2))
